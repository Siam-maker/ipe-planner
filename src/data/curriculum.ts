export function getCoursesForTerm(level: number, term: number): Course[] {
  const key = `${level}-${term}`;
  return RAW_CURRICULUM[key] || [];
}

export function getCourseKey(level: number, term: number, courseCode: string): string {
  return `${level}-${term}|${courseCode}`;
}

export function getTopicKey(level: number, term: number, courseCode: string, topicIndex: number): string {
  return `${level}-${term}|${courseCode}#${topicIndex}`;
}

export function getGradePoint(letter: string): number | null {
  const match = GRADES.find((g) => g[0] === letter);
  return match ? match[1] : null;
}

export function getGradeLetter(point: number): string {
  const match = GRADES.find((g) => Math.abs(g[1] - point) < 0.01);
  return match ? match[0] : 'F';
}
